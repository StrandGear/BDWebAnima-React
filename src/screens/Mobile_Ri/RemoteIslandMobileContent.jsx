const renderMobileParts = (parts, setActiveTab) =>
  parts.map((part, i) => {
    if (typeof part === "string") {
      return <React.Fragment key={i}>{part}</React.Fragment>;
    }

    if (part.tabLink) {
      return (
        <span
          key={i}
          onClick={() => setActiveTab && setActiveTab(part.tabLink)}
          className="ri-mobile-inline-link"
        >
          {part.text}
        </span>
      );
    }

    if (part.href) {
      return (
        <a
          key={i}
          className="ri-mobile-inline-link"
          href={part.href}
          target="_blank"
          rel="noopener noreferrer"
          download={part.isDownload ? part.href.split("/").pop() : undefined}
        >
          {part.text}
        </a>
      );
    }

    if (part.bold) {
      return <strong key={i}>{part.text}</strong>;
    }

    if (part.italic || part.cursive) {
      return <em key={i}>{part.text}</em>;
    }

    return null;
  });

export const RemoteIslandMobileTextContent = ({ content, setActiveTab }) => (
  <div className="ri-mobile-text-block">
    {content.map((node, i) => {
      const body = node.parts ? renderMobileParts(node.parts, setActiveTab) : node.text;

      if (node.type === "h") {
        return (
          <p className="ri-mobile-heading" key={i}>
            <strong>{body}</strong>
          </p>
        );
      }

      if (node.type === "block") {
        return (
          <p className="ri-mobile-address-block" key={i}>
            {body}
          </p>
        );
      }

      if (node.type === "ul") {
        return (
          <ul className="ri-mobile-list" key={i}>
            {node.items.map((item, j) => (
              <li key={j}>{item}</li>
            ))}
          </ul>
        );
      }

      return (
        <p className="ri-mobile-paragraph" key={i}>
          {body}
        </p>
      );
    })}
  </div>
);